#!/usr/bin/env python3
"""Generate the promotion class-name art font from ClassNameLetters.png."""
from PIL import Image
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "contents/promotion/ClassNameLetters.png")
DST = os.path.join(ROOT, "src/Core/Promotion/PromotionClassNameFont.c")

# (x0, y0, x1, y1) in the source image; x1/y1 are exclusive.
GLYPHS = {
    "A": (0, 1, 26, 24),
    "B": (32, 1, 50, 20),
    "C": (56, 1, 75, 20),
    "D": (80, 1, 94, 20),
    "E": (96, 1, 106, 20),
    "F": (112, 1, 122, 20),
    "G": (128, 1, 148, 20),
    "H": (152, 1, 166, 20),
    "I": (168, 1, 175, 20),
    "L": (175, 1, 186, 20),
    "M": (192, 1, 215, 20),
    "N": (216, 1, 230, 20),
    "P": (232, 1, 243, 20),
    "R": (0, 25, 14, 44),
    "S": (16, 25, 40, 44),
    "T": (40, 25, 51, 44),
    "V": (56, 25, 79, 44),
    "W": (80, 25, 99, 44),
    "Z": (104, 25, 128, 44),
    "K": (136, 25, 158, 44),
    "J": (160, 25, 186, 45),

    "a": (192, 24, 202, 36),
    "b": (16, 51, 26, 68),
    "c": (208, 24, 216, 36),
    "d": (32, 51, 42, 68),
    "e": (216, 24, 226, 36),
    "f": (48, 51, 57, 68),
    "g": (64, 48, 76, 65),
    "h": (80, 51, 90, 68),
    "i": (96, 51, 104, 68),
    "j": (248, 27, 256, 49),
    "k": (104, 51, 115, 68),
    "l": (120, 48, 127, 68),
    "m": (232, 24, 247, 36),
    "n": (192, 40, 203, 52),
    "o": (208, 40, 217, 52),
    "p": (144, 48, 155, 65),
    "q": (144, 48, 155, 65),
    "r": (160, 54, 167, 68),
    "s": (224, 40, 232, 52),
    "t": (167, 54, 176, 68),
    "u": (232, 40, 242, 52),
    "v": (192, 56, 202, 68),
    "w": (208, 56, 222, 68),
    "x": (224, 56, 235, 68),
    "y": (176, 48, 187, 65),
    "z": (240, 56, 250, 68),
}

# Uppercase fallbacks that are not in the sheet.  The FE6 class names rarely
# need them, but this keeps the renderer from dropping characters.
FLIP_H = {"p"}

GLYPHS["O"] = GLYPHS["o"]
GLYPHS["Q"] = GLYPHS["q"]
GLYPHS["U"] = GLYPHS["u"]
GLYPHS["X"] = GLYPHS["x"]
GLYPHS["Y"] = GLYPHS["y"]

im = Image.open(SRC).convert("P")
pal = im.getpalette()
pixels = im.load()

def color_to_bgr555(r, g, b):
    return ((b >> 3) << 10) | ((g >> 3) << 5) | (r >> 3)

palette = []
for i in range(16):
    if i == 0:
        palette.append(0)
    else:
        palette.append(color_to_bgr555(pal[i*3], pal[i*3+1], pal[i*3+2]))

tiles = bytearray()
glyphs = []
for ch, (x0, y0, x1, y1) in sorted(GLYPHS.items()):
    w, h = x1 - x0, y1 - y0
    tw, th = (w + 7) // 8, (h + 7) // 8
    tile_offset = len(tiles) // 32
    for ty in range(th):
        for tx in range(tw):
            for py in range(8):
                for px in range(8):
                    gx, gy = tx*8 + px, ty*8 + py
                    c = 0
                    if gx < w and gy < h:
                        sx = (w - 1 - gx) if ch in FLIP_H else gx
                        c = pixels[x0 + sx, y0 + gy] & 0xF
                        if c > 10:
                            c = 0
                    # 4bpp: low nibble is the left pixel
                    if px % 2 == 0:
                        tiles.append(c)
                    else:
                        tiles[-1] |= c << 4
    glyphs.append((ord(ch), w, h, tw, th, w + 1, tile_offset))

with open(DST, "w") as f:
    f.write("// Generated by tools/scripts/gen_promo_classname_font.py\n")
    f.write("// Source: contents/promotion/ClassNameLetters.png\n\n")
    f.write('#include "prelude.h"\n')
    f.write('#include "hacks/demo-promotion.h"\n\n')
    f.write("const u16 PromoClassNamePalette[16] = {\n\t")
    f.write(", ".join("0x%04X" % v for v in palette))
    f.write("\n};\n\n")
    f.write("const u8 PromoClassNameFontTiles[] = {\n")
    for i in range(0, len(tiles), 16):
        f.write("\t" + ", ".join("0x%02X" % b for b in tiles[i:i+16]) + ",\n")
    f.write("};\n\n")
    f.write("const struct PromoClassNameGlyph PromoClassNameGlyphs[] = {\n")
    for ch, w, h, tw, th, adv, off in glyphs:
        f.write("\t{ 0x%02X, %d, %d, %d, %d, %d, %d },\n" % (ch, w, h, tw, th, adv, off))
    f.write("};\n")
    f.write("\nconst int PromoClassNameGlyphCount = %d;\n" % len(glyphs))

print("wrote", DST, "tiles", len(tiles), "glyphs", len(glyphs))
